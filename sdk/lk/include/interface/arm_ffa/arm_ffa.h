/*
 * Minimal FF-A interface for ATF SPD=trusty (not an FF-A SPMC).
 * lib/arm_ffa reports INIT_FAILED so lib/sm uses the legacy SPD path.
 */
#pragma once

#include <stdint.h>
#include <sys/types.h>

enum ffa_error {
    FFA_ERROR_NOT_SUPPORTED = -1,
    FFA_ERROR_INVALID_PARAMETERS = -2,
    FFA_ERROR_NO_MEMORY = -3,
    FFA_ERROR_BUSY = -4,
    FFA_ERROR_INTERRUPTED = -5,
    FFA_ERROR_DENIED = -6,
    FFA_ERROR_RETRY = -7,
    FFA_ERROR_ABORTED = -8,
};

#define FFA_FRAMEWORK_MSG_FLAG (1U << 31)
#define FFA_FRAMEWORK_MSG_MASK 0xffU
#define FFA_FRAMEWORK_MSG_VM_CREATED_REQ 0x4U
#define FFA_FRAMEWORK_MSG_VM_CREATED_RESP 0x5U
#define FFA_FRAMEWORK_MSG_VM_DESTROYED_REQ 0x6U
#define FFA_FRAMEWORK_MSG_VM_DESTROYED_RESP 0x7U

#define FFA_VERSION(major, minor) (((uint32_t)(major) << 16) | (uint32_t)(minor))
#define FFA_VERSION_TO_MAJOR(v) ((uint32_t)(v) >> 16)
#define FFA_VERSION_TO_MINOR(v) ((uint32_t)(v) & 0xffffU)

#define SMC_FC_FFA_ERROR 0x84000060U
#define SMC_FC_FFA_SUCCESS 0x84000061U
#define SMC_FC64_FFA_SUCCESS 0xC4000061U
#define SMC_FC_FFA_INTERRUPT 0x84000062U
#define SMC_FC_FFA_VERSION 0x84000063U
#define SMC_FC_FFA_FEATURES 0x84000064U
#define SMC_FC_FFA_ID_GET 0x84000069U
#define SMC_FC_FFA_MSG_WAIT 0x8400006BU
#define SMC_FC_FFA_MSG_SEND_DIRECT_REQ 0x8400006FU
#define SMC_FC64_FFA_MSG_SEND_DIRECT_REQ 0xC400006FU
#define SMC_FC64_FFA_MSG_SEND_DIRECT_REQ2 0xC400008DU
#define SMC_FC_FFA_RUN 0x8400006DU
#define SMC_FC_FFA_MEM_RETRIEVE_REQ 0x84000075U
#define SMC_FC64_FFA_MEM_RETRIEVE_REQ 0xC4000075U
#define SMC_FC_FFA_MEM_RETRIEVE_RESP 0x84000076U
#define SMC_FC_FFA_MEM_RELINQUISH 0x84000077U
#define SMC_FC_FFA_MEM_RECLAIM 0x84000078U
#define SMC_FC_FFA_MEM_FRAG_RX 0x8400007AU
#define SMC_FC_FFA_MEM_FRAG_TX 0x8400007BU
#define FFA_FEATURES2_MEM_RETRIEVE_REQ_NS_BIT (1U << 1)

struct ffa_cons_mrd {
    uint64_t address;
    uint32_t page_count;
    uint32_t reserved;
};
